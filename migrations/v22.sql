-- Prima funzionalità in cui un membro qualsiasi scrive contenuto
-- libero visibile agli altri membri della lega (finora l'app importa
-- solo statistiche, o lascia scrivere solo l'admin/coorganizzatore).
--
-- Commenti solo su partite già giocate: `partite` rappresenta
-- strutturalmente solo partite disputate (gol_squadra_* not null,
-- importate a cose fatte da Fubles), quindi il vincolo di chiave
-- esterna su partite(id) è già la garanzia che serve — nessun flag
-- "partita conclusa" aggiuntivo.
